import { fetchWithTimeout, saveConnection } from './api';
export async function redeemPairingLink(link: string) {
  const url = new URL(link.trim());
  if (
    url.protocol !== 'https:' ||
    url.username ||
    url.password ||
    url.pathname !== '/' ||
    url.search
  )
    throw Error('Use the HTTPS pairing link generated by your server.');
  const ticket = new URLSearchParams(url.hash.slice(1)).get('pairing');
  if (!ticket || !/^[A-Za-z0-9_-]{43}$/.test(ticket)) throw Error('The pairing ticket is invalid.');
  const response = await fetchWithTimeout(
    url.origin + '/mobile/pair',
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ ticket }),
    },
    20000,
  );
  if (!response.ok) throw Error('Pairing expired or was already used. Generate another link.');
  let data: { token?: string };
  try {
    data = await response.json();
  } catch {
    throw Error(
      'Your finance server returned an unreadable response. Check its HTTPS address and try again.',
    );
  }
  await saveConnection(url.origin, data.token ?? '');
}
